/**
 * "Overview" page of the plugin — first sub-page under the Double Youpï menu
 * (and therefore the landing page when clicking the parent menu item).
 *
 * Renders a grid of cards, one per module in the catalog, showing its status
 * (active / inactive / coming soon) and a toggle to enable or disable it.
 * A module toggle only takes effect on the next page load — disabled modules
 * have their boot() call skipped inside ModuleRegistry.
 *
 * This is not a module in the AbstractModule sense: it is a core page, hooked
 * by Plugin::boot() before ModuleRegistry::boot() so that it appears first
 * in the AdminMenu order.
 */
final class OverviewPage {

	/**
	 * Slug IDENTICAL to the parent slug — the Overview page IS the home
	 * of the Double Youpï menu, so we want a single URL (`?page=doubleyoupi`)
	 * rather than a duplicate `doubleyoupi-overview` that would create two
	 * separate items in the chipbar. AdminMenu detects this case (first item ==
	 * parent SLUG) and renames the sub-menu auto-generated by `add_menu_page()`
	 * instead of removing it — avoiding the need to register a second sub-menu ourselves.
	 */
	private const PAGE_SLUG       = AdminMenu::SLUG;
	private const FORM_ACTION     = 'doubleyoupi_modules_toggle';
	private const NONCE_NAME      = '_doubleyoupi_modules_nonce';
	private const FIELD_PREFIX    = 'doubleyoupi_module_';
	private const NOTICE_TRANSIENT = 'doubleyoupi_overview_notice';

	/**
	 * AJAX action (admin-ajax) for the auto-save toggle. Each switch flip
	 * immediately persists the module state without submitting the form —
	 * by the time the user leaves the page, the setting is already written
	 * to the database. The classic POST form (handle_form) remains as a
	 * no-JavaScript fallback.
	 */
	private const AJAX_ACTION     = 'doubleyoupi_modules_toggle';

	/**
	 * Modules whose toggle changes the GLOBAL appearance of the admin and
	 * therefore requires a page reload to apply (or remove) the visual effect.
	 * For these — Refined Admin Dashboard chief among them — the card shows a
	 * discreet "Reload to apply" button whenever its state differs from what it
	 * was at page load. Other modules do not affect the current admin chrome:
	 * auto-save alone is sufficient, no reload needed.
	 *
	 * @var string[]
	 */
	private const RELOAD_REQUIRED_IDS = [ 'admin' ];

	/**
	 * Must be called from Plugin::boot() BEFORE ModuleRegistry::boot() so that
	 * this page lands first in AdminMenu and becomes the home page.
	 */
	public static function register(): void {
		AdminMenu::add_page(
			__( 'Double Youpi · Overview', 'doubleyoupi-refined-media-library' ),
			__( 'Overview', 'doubleyoupi-refined-media-library' ),
			self::PAGE_SLUG,
			[ self::class, 'render' ]
		);

		add_action( 'admin_post_' . self::FORM_ACTION, [ self::class, 'handle_form' ] );
		add_action( 'wp_ajax_' . self::AJAX_ACTION, [ self::class, 'ajax_toggle' ] );
		add_action( 'admin_enqueue_scripts', [ self::class, 'maybe_enqueue_styles' ] );
	}

	/**
	 * Enqueues the Double Youpï CSS on all plugin admin pages:
	 *   - Overview (top-level `?page=doubleyoupi`)
	 *   - Module sub-pages (`?page=doubleyoupi-admin`, performance,
	 *     static, media-library, backups, staging…)
	 *
	 * The hook provided by WP is `toplevel_page_doubleyoupi` for the home page,
	 * and `{parent-slug}_page_doubleyoupi-{module}` for sub-pages. The
	 * `{parent-slug}_` prefix depends on the parent menu_title (= "Double Youpï"
	 * → "double-youpi"); we avoid hardcoding this prefix by checking for the
	 * string `doubleyoupi` in the hook, which covers both cases and remains
	 * resilient to any future rename of the menu title.
	 *
	 * The compiled CSS contains ALL Double Youpï styles (overview shell +
	 * sub-page shell + light fallback tokens), so a single URL needs to be
	 * enqueued for both contexts.
	 */
	public static function maybe_enqueue_styles( string $hook ): void {
		// The hook always contains `doubleyoupi` for our pages, in one of
		// two forms: `toplevel_page_doubleyoupi` or
		// `{parent}_page_doubleyoupi-{slug}`. str_contains covers both.
		if ( ! str_contains( $hook, 'doubleyoupi' ) ) {
			return;
		}
		$css = DOUBLEYOUPI_DIR . 'assets/css/admin-overview.css';
		if ( ! file_exists( $css ) ) {
			return;
		}
		// Cache-buster: filemtime on the compiled file ensures that SCSS
		// iterations are refreshed without a manual bump of DOUBLEYOUPI_VERSION.
		$version = (string) ( filemtime( $css ) ?: DOUBLEYOUPI_VERSION );
		wp_enqueue_style(
			'doubleyoupi-admin-overview',
			DOUBLEYOUPI_URL . 'assets/css/admin-overview.css',
			[],
			$version
		);

		// SVG sprite: injected in admin_footer. Sub-pages can use it
		// via IconSprite::svg('admin') / ('media-library') / etc.
		IconSprite::queue();

		// Auto-save toggle script: ONLY on the home (Overview page),
		// the sole page that renders the activation grid. Module sub-pages
		// load the same CSS but have no switches to control.
		if ( 'toplevel_page_' . self::PAGE_SLUG !== $hook ) {
			return;
		}
		$js = DOUBLEYOUPI_DIR . 'assets/js/overview.js';
		if ( ! file_exists( $js ) ) {
			return;
		}
		$js_version = (string) ( filemtime( $js ) ?: DOUBLEYOUPI_VERSION );
		// `updates` dependency: provides window.wp.updates (and its nonce) for
		// installing a free module hosted on WordPress.org directly from the
		// showcase modal. Degrades gracefully if unavailable (falls back to a
		// link to the native plugin installer screen).
		wp_enqueue_script(
			'doubleyoupi-overview',
			DOUBLEYOUPI_URL . 'assets/js/overview.js',
			[ 'updates' ],
			$js_version,
			true
		);
		wp_localize_script(
			'doubleyoupi-overview',
			'doubleyoupiOverview',
			[
				'ajaxUrl'       => admin_url( 'admin-ajax.php' ),
				'action'        => self::AJAX_ACTION,
				'nonce'         => wp_create_nonce( self::AJAX_ACTION ),
				'reloadModules' => array_values( self::RELOAD_REQUIRED_IDS ),
				'installBaseUrl' => self_admin_url( 'plugin-install.php?tab=search&type=term&s=' ),
				'i18n'          => [
					'statusActive'   => __( 'Active', 'doubleyoupi-refined-media-library' ),
					'statusInactive' => __( 'Disabled', 'doubleyoupi-refined-media-library' ),
					'switchOn'       => __( 'Enabled', 'doubleyoupi-refined-media-library' ),
					'switchOff'      => __( 'Disabled', 'doubleyoupi-refined-media-library' ),
					'settings'       => __( 'Settings', 'doubleyoupi-refined-media-library' ),
					'saveError'      => __( 'Could not save. Please retry.', 'doubleyoupi-refined-media-library' ),
					'install'        => __( 'Install for free', 'doubleyoupi-refined-media-library' ),
					'installing'     => __( 'Installing…', 'doubleyoupi-refined-media-library' ),
					'installed'      => __( 'Installed ✓', 'doubleyoupi-refined-media-library' ),
					'installError'   => __( 'Install failed, open the installer', 'doubleyoupi-refined-media-library' ),
					'comingSoon'     => __( 'Soon on WordPress.org', 'doubleyoupi-refined-media-library' ),
					'discover'       => __( 'Discover on doubleyoupi.com', 'doubleyoupi-refined-media-library' ),
					'free'           => __( 'Free', 'doubleyoupi-refined-media-library' ),
					'suite'          => __( 'Suite', 'doubleyoupi-refined-media-library' ),
				],
			]
		);
	}

	/**
	 * POST handler: receives the toggle form submission and persists the state.
	 */
	public static function handle_form(): void {
		if ( ! current_user_can( AdminMenu::CAPABILITY ) ) {
			wp_die( esc_html__( 'Access denied.', 'doubleyoupi-refined-media-library' ), '', [ 'response' => 403 ] );
		}
		check_admin_referer( self::FORM_ACTION, self::NONCE_NAME );

		// For each AVAILABLE module, read the checkbox value from $_POST.
		// Absent = disabled (browsers do not submit unchecked checkboxes).
		$posted_keys = array_keys( $_POST ); // phpcs:ignore WordPress.Security.NonceVerification.Missing
		$count_changes = 0;

		foreach ( ModuleCatalog::available_ids() as $module_id ) {
			$field_name = self::FIELD_PREFIX . str_replace( '-', '_', $module_id );
			$enabled    = in_array( $field_name, $posted_keys, true );
			$current    = ModuleSettings::is_enabled( $module_id );
			if ( $current !== $enabled ) {
				ModuleSettings::set_enabled( $module_id, $enabled );
				$count_changes++;
			}
		}

		set_transient(
			self::NOTICE_TRANSIENT,
			$count_changes > 0
				? __( 'Modules updated. Reload the page to see the effects.', 'doubleyoupi-refined-media-library' )
				: __( 'No changes to save.', 'doubleyoupi-refined-media-library' ),
			30
		);

		wp_safe_redirect( admin_url( 'admin.php?page=' . self::PAGE_SLUG ) );
		exit;
	}

	/**
	 * AJAX handler: persists the state of ONE module when its switch is toggled.
	 *
	 * Returns the recalculated counter (X / Y active modules) so the hero can
	 * be refreshed without a page reload, and `requires_reload` so the front end
	 * knows whether to show the "Reload to apply" button (Refined Admin Dashboard case).
	 */
	public static function ajax_toggle(): void {
		if ( ! current_user_can( AdminMenu::CAPABILITY ) ) {
			wp_send_json_error( [ 'message' => __( 'Access denied.', 'doubleyoupi-refined-media-library' ) ], 403 );
		}
		check_ajax_referer( self::AJAX_ACTION, 'nonce' );

		// sanitize_key preserves hyphens in module IDs (media-library, seo-a11y…).
		$module_id = isset( $_POST['module_id'] ) ? sanitize_key( wp_unslash( $_POST['module_id'] ) ) : '';
		$enabled   = isset( $_POST['enabled'] ) && '1' === $_POST['enabled'];

		if ( ! in_array( $module_id, ModuleCatalog::available_ids(), true ) ) {
			wp_send_json_error( [ 'message' => __( 'Unknown module.', 'doubleyoupi-refined-media-library' ) ], 400 );
		}

		ModuleSettings::set_enabled( $module_id, $enabled );

		// "X / Y" counter recalculated server-side — source of truth after the write.
		$available_ids = ModuleCatalog::available_ids();
		$enabled_count = 0;
		foreach ( $available_ids as $id ) {
			if ( ModuleSettings::is_enabled( $id ) ) {
				$enabled_count++;
			}
		}

		wp_send_json_success(
			[
				'module_id'       => $module_id,
				'enabled'         => $enabled,
				'enabled_count'   => $enabled_count,
				'available_count' => count( $available_ids ),
				'requires_reload' => in_array( $module_id, self::RELOAD_REQUIRED_IDS, true ),
			]
		);
	}

	/**
	 * Renders the page HTML.
	 */
	public static function render(): void {
		if ( ! current_user_can( AdminMenu::CAPABILITY ) ) {
			return;
		}

		// Split into four buckets for a clear ordering in the grid:
		//   1. present  : module(s) actually bundled in this plugin (toggle active)
		//   2. free     : range modules that are available and free (showcase + install)
		//   3. paid     : range modules that are available and paid (showcase + suite link)
		//   4. soon     : "coming soon" → separate compact section, no action
		// In the full suite, all available modules are registered → they all
		// fall into "present" and the layout stays exactly as before.
		$present = [];
		$free    = [];
		$paid    = [];
		$soon    = [];
		foreach ( ModuleCatalog::all() as $module ) {
			if ( $module['status'] !== ModuleCatalog::STATUS_AVAILABLE ) {
				$soon[] = $module;
				continue;
			}
			if ( ModuleRegistry::has( $module['id'] ) ) {
				$present[] = $module;
				continue;
			}
			$tier = ModuleCatalog::vitrine( $module['id'] )['tier'] ?? 'paid';
			if ( 'free' === $tier ) {
				$free[] = $module;
			} else {
				$paid[] = $module;
			}
		}
		$grid_modules = array_merge( $present, $free, $paid );

		$notice  = get_transient( self::NOTICE_TRANSIENT );
		if ( $notice ) {
			delete_transient( self::NOTICE_TRANSIENT );
		}

		// SVG sprite: queued at render time so IconSprite::print_sprite()
		// inlines it in admin_footer before the <use> elements are parsed.
		IconSprite::queue();

		// "X / Y active modules" counter — metadata used in the hero.
		// `available_ids()` returns only modules that are actually implemented
		// (status STATUS_AVAILABLE), so the ratio reflects the functional reality.
		$available_ids   = ModuleCatalog::available_ids();
		$enabled_count   = 0;
		foreach ( $available_ids as $id ) {
			if ( ModuleSettings::is_enabled( $id ) ) {
				$enabled_count++;
			}
		}
		$available_count = count( $available_ids );

		// Extra class to signal that the Admin module is ACTIVE at render time.
		// Allows `_admin-bridge.scss` styles to kick in even when body.dy-admin
		// is not yet applied (typically during View Transitions API transitions).
		$admin_active     = ModuleSettings::is_enabled( 'admin' );
		$wrap_extra_class = $admin_active ? ' dy-overview--admin-on' : '';

		// In solo mode (SoloConfig present → single bundled module), the hero
		// foregrounds the PLUGIN NAME (large, white) beneath the "Double Youpï"
		// brand (in accent), and the tagline describes THAT module. In the suite,
		// we keep the range pitch and the "Double Youpï" title.
		$tagline     = __( 'Modular suite for pros who ship WordPress sites. Enable the modules you need, disable the rest.', 'doubleyoupi-refined-media-library' );
		$plugin_name = '';
		$quip        = '';
		if ( class_exists( '\\DoubleYoupi\\Core\\SoloConfig' ) ) {
			$present = \DoubleYoupi\Core\SoloConfig::present_modules();
			$entry   = ! empty( $present ) ? ModuleCatalog::find( (string) $present[0] ) : null;
			if ( $entry && ! empty( $entry['description'] ) ) {
				$tagline = (string) $entry['description'];
			}
			if ( $entry && ! empty( $entry['name'] ) ) {
				$plugin_name = (string) $entry['name'];
			}
			// Random quip in place of the "X / Y active modules" counter
			// (meaningless in solo mode). Draws from a generic pool + module-specific ones.
			if ( ! empty( $present ) ) {
				$quip = HeroQuips::random( (string) $present[0] );
			}
		}
		?>
		<div class="wrap dy-overview<?php echo esc_attr( $wrap_extra_class ); ?>">

			<header class="dy-overview__hero">
				<?php
				// "Double Youpï" split server-side to preserve i18n.
				$brand_segments = explode( ' ', __( 'Double Youpï', 'doubleyoupi-refined-media-library' ), 2 );
				$brand_html     = esc_html( $brand_segments[0] );
				if ( isset( $brand_segments[1] ) ) {
					$brand_html .= '<span class="dy-overview__brand-mark">' . esc_html( $brand_segments[1] ) . '</span>';
				}
				?>
				<?php if ( '' !== $plugin_name ) : ?>
					<span class="dy-overview__brand"><?php echo $brand_html; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped ?></span>
					<h1 class="dy-overview__title dy-overview__title--solo"><?php echo esc_html( $plugin_name ); ?></h1>
				<?php else : ?>
					<h1 class="dy-overview__title"><?php echo $brand_html; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped ?></h1>
				<?php endif; ?>
				<p class="dy-overview__tagline">
					<?php echo esc_html( $tagline ); ?>
				</p>
				<div class="dy-overview__hero-meta" aria-label="<?php esc_attr_e( 'Suite information', 'doubleyoupi-refined-media-library' ); ?>">
					<?php if ( '' !== $quip ) : ?>
						<?php // Solo: random quip (accented) in place of the counter. ?>
						<span class="dy-overview__hero-quip"><?php echo esc_html( $quip ); ?></span>
					<?php else : ?>
						<span class="dy-overview__hero-meta-row" data-dy-counter data-state="<?php echo $enabled_count > 0 ? 'active' : 'idle'; ?>">
							<span class="dy-overview__hero-meta-value"><?php echo (int) $enabled_count; ?>&nbsp;/&nbsp;<?php echo (int) $available_count; ?></span>
							<?php esc_html_e( 'active modules', 'doubleyoupi-refined-media-library' ); ?>
						</span>
					<?php endif; ?>
					<span class="dy-overview__hero-meta-row">
						<span class="dy-overview__hero-meta-value">v<?php echo esc_html( DOUBLEYOUPI_VERSION ); ?></span>
					</span>
				</div>
			</header>

			<?php
			// Admin notice placement target: WordPress (common.js) moves all
			// .notice elements to just before this element, at full width and in
			// normal document flow. Without it, WP inserts them after the first
			// <h1> (inside the flex hero), squashing them into a narrow column.
			?>
			<hr class="wp-header-end">

			<?php if ( $notice ) : ?>
				<div class="notice notice-success is-dismissible"><p><?php echo esc_html( $notice ); ?></p></div>
			<?php endif; ?>

			<?php
			/**
			 * Room above the module grid (first-run card of a module, for
			 * instance). Modules listen; the core stays uncoupled.
			 */
			do_action( 'doubleyoupi_overview_before_grid' );
			?>

			<form method="post" action="<?php echo esc_url( admin_url( 'admin-post.php' ) ); ?>">
				<input type="hidden" name="action" value="<?php echo esc_attr( self::FORM_ACTION ); ?>">
				<?php wp_nonce_field( self::FORM_ACTION, self::NONCE_NAME ); ?>

				<div class="dy-overview__grid">
					<?php
					$i = 0;
					foreach ( $grid_modules as $module ) {
						self::render_card( $module, $i++ );
					}
					?>
				</div>

				<?php // No-JS fallback only: with JS enabled, auto-save hides this entire area (see _toggle-feedback.scss). Feedback is provided by a "✓ Saved" indicator next to each toggle. ?>
				<p class="dy-overview__actions">
					<?php submit_button( __( 'Save modules', 'doubleyoupi-refined-media-library' ), 'primary', 'submit', false ); ?>
				</p>
			</form>

			<?php
			/**
			 * Allows modules to inject additional sections below the activation grid.
			 * Used by Toolkit to render "Quick Tools".
			 *
			 * No direct coupling between core and modules: we fire, they listen.
			 */
			self::render_soon_section( $soon );

			do_action( 'doubleyoupi_overview_after_modules_grid' );
			?>

			<?php self::render_modal(); ?>
			<?php self::render_support(); ?>
			<?php self::render_feedback_band(); ?>
		</div>
		<?php
	}

	/**
	 * Renders a module card (extracted for readability).
	 *
	 * @param array{id:string, name:string, description:string, icon:string, status:string, settings_url:?string} $module
	 * @param int $index Position in the grid — used for the staggered entry animation (--dya-card-i).
	 */
	private static function render_card( array $module, int $index = 0 ): void {
		$is_available  = $module['status'] === ModuleCatalog::STATUS_AVAILABLE;

		// Range "showcase" card: a module that exists as a product (status
		// available) but is NOT bundled in THIS plugin (standalone WP.org plugin
		// case). In the full suite, all available modules are registered via
		// ModuleRegistry → this branch never triggers, so the suite rendering
		// remains strictly unchanged.
		if ( $is_available && ! ModuleRegistry::has( $module['id'] ) ) {
			self::render_vitrine_card( $module, $index );
			return;
		}

		$is_enabled    = $is_available && ModuleSettings::is_enabled( $module['id'] );
		$field_name    = self::FIELD_PREFIX . str_replace( '-', '_', $module['id'] );
		$status_label  = match ( true ) {
			! $is_available => __( 'Coming soon', 'doubleyoupi-refined-media-library' ),
			$is_enabled     => __( 'Active', 'doubleyoupi-refined-media-library' ),
			default         => __( 'Disabled', 'doubleyoupi-refined-media-library' ),
		};
		$status_class  = match ( true ) {
			! $is_available => 'is-soon',
			$is_enabled     => 'is-active',
			default         => 'is-inactive',
		};

		// Icon ID in the SVG sprite: derived directly from the module ID.
		// Every module in the catalog has a matching symbol in
		// assets/images/dy-modules-sprite.svg (id="dy-icon-{module-id}").
		$icon_svg = IconSprite::svg( $module['id'], 'dy-icon--module', 24 );

		// Settings URL exposed as a data attribute: JS dynamically adds or removes
		// the "Settings" link when a module is toggled without a page reload.
		$settings_url    = $is_available && ! empty( $module['settings_url'] ) ? (string) $module['settings_url'] : '';
		$requires_reload = $is_available && in_array( $module['id'], self::RELOAD_REQUIRED_IDS, true );
		?>
		<div class="dy-overview__card <?php echo esc_attr( $status_class ); ?>"
		     data-module-id="<?php echo esc_attr( $module['id'] ); ?>"
		     <?php if ( $settings_url ) : ?>data-settings-url="<?php echo esc_url( $settings_url ); ?>"<?php endif; ?>
		     style="--dya-card-i: <?php echo (int) $index; ?>;">
			<div class="dy-overview__card-head">
				<span class="dy-overview__icon-tile" aria-hidden="true">
					<?php echo $icon_svg; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- pre-escaped SVG markup from IconSprite::svg() ?>
				</span>
				<span class="dy-overview__status"><?php echo esc_html( $status_label ); ?></span>
			</div>
			<h2 class="dy-overview__name"><?php echo esc_html( $module['name'] ); ?></h2>
			<p class="dy-overview__desc"><?php echo esc_html( $module['description'] ); ?></p>
			<div class="dy-overview__card-foot">
				<?php if ( $is_available ) : ?>
					<label class="dy-overview__switch">
						<input type="checkbox"
						       name="<?php echo esc_attr( $field_name ); ?>"
						       value="1"
						       <?php checked( $is_enabled ); ?>>
						<span class="dy-overview__switch-track"></span>
						<span class="dy-overview__switch-label">
							<?php echo $is_enabled
								? esc_html__( 'Enabled', 'doubleyoupi-refined-media-library' )
								: esc_html__( 'Disabled', 'doubleyoupi-refined-media-library' ); ?>
						</span>
					</label>
					<?php // Transient "✓ Saved" confirmation beside the toggle (revealed by overview.js after auto-save). ?>
					<span class="dy-overview__saved" role="status" aria-live="polite" hidden>
						<svg class="dy-overview__saved-icon" viewBox="0 0 12 12" aria-hidden="true">
							<path fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" d="M2.5 6.2 5 8.5l4.5-5"/>
						</svg>
						<span class="dy-overview__saved-text"><?php esc_html_e( 'Saved', 'doubleyoupi-refined-media-library' ); ?></span>
					</span>
					<?php if ( $settings_url && $is_enabled ) : ?>
						<a href="<?php echo esc_url( $settings_url ); ?>" class="dy-overview__settings-link">
							<?php esc_html_e( 'Settings', 'doubleyoupi-refined-media-library' ); ?>
						</a>
					<?php endif; ?>
					<?php if ( $requires_reload ) : ?>
						<?php
						/*
						 * Discreet "Reload to apply" button: hidden by default, revealed
						 * by JS only when the Admin module state differs from what it was
						 * at page load (whether activated OR deactivated). The admin
						 * redesign repaints the entire chrome — a reload is needed to see
						 * it apply or disappear. hidden = takes no space until relevant.
						 */
						?>
						<button type="button" class="dy-overview__reload" data-dy-reload hidden>
							<svg class="dy-overview__reload-icon" viewBox="0 0 24 24" width="13" height="13" aria-hidden="true" focusable="false">
								<path fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"
