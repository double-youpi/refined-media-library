	/**
	 * Feedback form URL: set by the solo build (SoloConfig::support),
	 * otherwise falls back to the default brand URL (suite + fallback).
	 */
	private static function feedback_url(): string {
		$config_class = 'DoubleYoupi\\Core\\SoloConfig';
		if ( class_exists( $config_class ) ) {
			$s = $config_class::support();
			if ( ! empty( $s['feedback_url'] ) ) {
