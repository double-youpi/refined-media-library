/**
 * Main Double Youpi menu in the WordPress admin.
 *
 * Modules register themselves via AdminMenu::add_page() during their boot()
 * (which runs on plugins_loaded, before the admin_menu hook fires).
 * AdminMenu::build() then constructs the full menu on the admin_menu hook.
 *
 * WordPress menu pattern:
 *   - add_menu_page() automatically creates a duplicate of the parent as the first submenu item.
 *   - We remove that duplicate via remove_submenu_page().
 *   - Each module keeps its own slug (doubleyoupi-admin, etc.).
 *   - Clicking "Double Youpi" (the parent) displays the first module's content.
 */
final class AdminMenu {

	public const SLUG       = 'doubleyoupi';
	public const CAPABILITY = 'manage_options';

	/** @var array<array{page_title:string, menu_title:string, slug:string, callback:callable}> */
	private static array $pages = [];

	/**
	 * Hooks AdminMenu::build() and the WP duplicate-cleanup onto admin_menu.
	 * Called from Plugin::boot().
	 */
	public static function register(): void {
		add_action( 'admin_menu', [ self::class, 'build' ] );
		// Priority 999: after all plugins have registered their menus,
		// remove the duplicate auto-generated by add_menu_page().
		add_action( 'admin_menu', [ self::class, 'remove_auto_submenu' ], 999 );
	}

	/**
	 * Registers a sub-page under the Double Youpi menu.
	 *
	 * Must be called during a module's boot() (i.e., on plugins_loaded),
	 * before the admin_menu hook fires.
	 *
	 * The first call defines the landing page for the top-level menu.
	 *
	 * @param callable $callback Valid PHP callable that renders the page.
	 */
	public static function add_page(
		string   $page_title,
		string   $menu_title,
		string   $slug,
		callable $callback
	): void {
		self::$pages[] = compact( 'page_title', 'menu_title', 'slug', 'callback' );
	}

	/**
	 * Builds the WordPress menu from the pages registered by modules.
	 * Callback for the admin_menu hook — do not call directly.
	 */
	public static function build(): void {
		if ( empty( self::$pages ) ) {
			return;
		}

		$first = self::$pages[0];

		// When only ONE module is present (a single standalone plugin), its tab
		// is labelled "Settings" rather than the module name — the module name is
		// already shown in the hero and would be redundant. As soon as there are
		// multiple modules (the suite, or several standalone plugins co-installed),
		// each keeps its own name. The rename is scoped to solo context (SoloConfig
		// present) so the suite always shows module names even if only one is active.
		$module_pages    = array_filter( self::$pages, static fn( array $p ): bool => $p['slug'] !== self::SLUG );
		$rename_settings = 1 === count( $module_pages ) && class_exists( '\\DoubleYoupi\\Core\\SoloConfig' );

		// A solo may bundle satellite modules that register their own page
		// (Refined Admin Dashboard ships the Toolkit as "Tools"): what makes a
		// solo "mono" is the number of PRESENT modules, not the number of
		// pages. With one present module, its settings page is labelled
		// "Settings" and the top-level menu carries the plugin name; the
		// satellite pages keep their own labels.
		$settings_slug = '';
		if ( class_exists( '\\DoubleYoupi\\Core\\SoloConfig' ) && method_exists( '\\DoubleYoupi\\Core\\SoloConfig', 'present_modules' ) ) {
			$present = (array) \DoubleYoupi\Core\SoloConfig::present_modules();
			if ( 1 === count( $present ) ) {
				$rename_settings = true;
				$settings_slug   = self::SLUG . '-' . (string) reset( $present );
			}
		}

		// Top-level menu label. In MONO-SOLO mode (one module + solo context),
		// the menu carries the PLUGIN NAME (e.g., "Refined Media Library") rather
		// than the "Double Youpi" umbrella: the user finds their plugin under the
		// name they installed. Once there are ≥ 2 modules (suite, or multiple
		// standalone plugins co-installed), the "Double Youpi" umbrella is meaningful again.
		// The Overview page remains the landing page in both cases.
		$top_label = 'Double Youpi';
		if ( $rename_settings && method_exists( '\\DoubleYoupi\\Core\\SoloConfig', 'plugin_name' ) ) {
			$name = (string) \DoubleYoupi\Core\SoloConfig::plugin_name();
			if ( '' !== $name ) {
				$top_label = $name;
			}
		}

		// Top-level: same callback as the first active module.
		// add_menu_page() automatically generates a duplicate submenu item (slug
		// = parent SLUG). If the first registered page wants to CLAIM that slug
		// (as OverviewPage does), we leave the auto-generated submenu in place
		// and rename it instead of re-declaring an entry — this avoids having two
		// distinct items (`?page=doubleyoupi` + `?page=doubleyoupi-overview`)
		// that render the same page.
		add_menu_page(
			$top_label,
			$top_label,
			self::CAPABILITY,
			self::SLUG,
			$first['callback'],
			self::icon_data_uri(),
			81
		);

		// Module sub-menus — SKIP the first page if its slug matches the
		// parent slug (the auto-generated submenu fills that role; it will be
		// renamed in remove_auto_submenu).
		foreach ( self::$pages as $i => $page ) {
			if ( 0 === $i && $page['slug'] === self::SLUG ) {
				continue;
			}
			$is_settings = $rename_settings && ( '' === $settings_slug || $page['slug'] === $settings_slug );
			add_submenu_page(
				self::SLUG,
				$page['page_title'],
				$is_settings ? __( 'Settings', 'doubleyoupi-refined-media-library' ) : $page['menu_title'],
				self::CAPABILITY,
				$page['slug'],
				$page['callback']
			);
		}
	}

	/**
	 * Cleans up the submenu auto-generated by `add_menu_page()`:
	 *   - If the first registered page carries the parent slug (Overview),
	 *     RENAME that submenu entry using its menu_title (instead of the
	 *     duplicate "Double Youpi" label).
	 *   - Otherwise, remove it — the historic behaviour.
	 * Priority 999 to run after all add_submenu_page() calls, when the
	 * global `$submenu` array is stable.
	 */
	public static function remove_auto_submenu(): void {
		global $submenu;

		$first = self::$pages[0] ?? null;
		$first_is_parent = $first && $first['slug'] === self::SLUG;

		if ( $first_is_parent && isset( $submenu[ self::SLUG ] ) ) {
			foreach ( $submenu[ self::SLUG ] as $i => $entry ) {
				if ( is_array( $entry ) && ( $entry[2] ?? '' ) === self::SLUG ) {
					$submenu[ self::SLUG ][ $i ][0] = $first['menu_title'];
					return;
				}
			}
		}

		remove_submenu_page( self::SLUG, self::SLUG );
	}

	private static function icon_data_uri(): string {
		$path = DOUBLEYOUPI_DIR . 'assets/img/icon-doubleyoupi.svg';
		if ( ! is_readable( $path ) ) {
			return 'dashicons-admin-generic';
		}
		// phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
		return 'data:image/svg+xml;base64,' . base64_encode( (string) file_get_contents( $path ) );
	}
}
