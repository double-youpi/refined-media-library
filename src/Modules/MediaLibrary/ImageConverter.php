<?php declare(strict_types=1);
namespace DoubleYoupi\Modules\MediaLibrary;

use DoubleYoupi\Core\AbstractModule;
use DoubleYoupi\Core\Logger;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * WebP / AVIF conversion of images on upload.
 *
 * Logic ported from legacy/performance/class-image-converter.php and adapted:
 *  - Namespace: DoubleYoupi\Modules\MediaLibrary (no cross-module coupling)
 *  - Options read from Settings:: instead of the legacy performance options
 *  - Hook: wp_generate_attachment_metadata @20 (after WP has created the thumbnails)
 *
 * Conversion generates a "double-extension" variant alongside the source file:
 *   uploads/2024/05/photo.jpg → uploads/2024/05/photo.jpg.webp
 *
 * Variants are consumed by Module 04 (Optimisation) to inject
 * <picture>/<source> tags into the output HTML.
 */
class ImageConverter extends AbstractModule {

	private const MIN_BYTES = 2048;

	public function id(): string {
		return 'media-library-converter';
	}

	public function name(): string {
		return 'Refined Media Library — Image Converter';
	}

	public function is_available(): bool {
		return self::supported_formats()['backend'] !== 'none';
	}

	public function boot(): void {
		// Priority 20: runs after WP (priority 10) which generates the thumbnails.
		// Allows converting the original AND all intermediate sizes.
		add_filter( 'wp_generate_attachment_metadata', [ $this, 'on_generate_metadata' ], 20, 2 );
	}

	public function on_generate_metadata( array $metadata, int $attachment_id ): array {
		// Short-circuit: if Module 04 (Optimisation) has registered itself via the
		// `doubleyoupi_perf_image_converter` filter, it owns the conversion pipeline.
		// M07 defers to M04's hook (which has its own options, its own quality setting,
		// and stores a post_meta for the media indicator).
		if ( null !== apply_filters( 'doubleyoupi_perf_image_converter', null ) ) {
			return $metadata;
		}

		if ( ! Settings::webp_upload_enabled() && ! Settings::avif_upload_enabled() ) {
			return $metadata;
		}

		$file = get_attached_file( $attachment_id );
		if ( $file ) {
			self::convert_for( $file );
		}

		// Also convert all sizes generated by WP (thumbnail, medium, etc.).
		if ( ! empty( $metadata['sizes'] ) && ! empty( $metadata['file'] ) ) {
			$upload_dir = wp_upload_dir();
			$subdir     = trailingslashit( $upload_dir['basedir'] ) . dirname( $metadata['file'] );
			foreach ( $metadata['sizes'] as $size ) {
				if ( ! empty( $size['file'] ) ) {
					self::convert_for( trailingslashit( $subdir ) . $size['file'] );
				}
			}
		}

		return $metadata;
	}

	// -------------------------------------------------------------------------
	// Static API — can be called from other contexts (CLI, import, etc.)
	// -------------------------------------------------------------------------

	/**
	 * @return array{ok:bool, webp:array{done:bool, reason?:string, bytes?:int, saved?:int}, avif:array{done:bool, reason?:string, bytes?:int, saved?:int}}
	 */
	public static function convert_for( string $source_path ): array {
		$result = [
			'ok'   => false,
			'webp' => [ 'done' => false ],
			'avif' => [ 'done' => false ],
		];

		if ( ! is_file( $source_path ) || ! is_readable( $source_path ) ) {
			$result['webp']['reason'] = $result['avif']['reason'] = 'unreadable';
			return $result;
		}

		$ext = strtolower( (string) pathinfo( $source_path, PATHINFO_EXTENSION ) );
		if ( ! in_array( $ext, [ 'jpg', 'jpeg', 'png', 'gif' ], true ) ) {
			$result['webp']['reason'] = $result['avif']['reason'] = 'unsupported_ext';
			return $result;
		}

		if ( (int) filesize( $source_path ) < self::MIN_BYTES ) {
			$result['webp']['reason'] = $result['avif']['reason'] = 'too_small';
			return $result;
		}

		if ( $ext === 'gif' && self::is_animated_gif( $source_path ) ) {
			$result['webp']['reason'] = $result['avif']['reason'] = 'animated_gif';
			return $result;
		}

		$support    = self::supported_formats();
		$want_webp  = Settings::webp_upload_enabled();
		$want_avif  = Settings::avif_upload_enabled();
		$quality    = Settings::image_quality();

		if ( ! $want_webp && ! $want_avif ) {
			$result['webp']['reason'] = $result['avif']['reason'] = 'disabled';
			return $result;
		}

		if ( $support['backend'] === 'none' ) {
			$result['webp']['reason'] = $result['avif']['reason'] = 'no_backend';
			return $result;
		}

		if ( $want_webp ) {
			$result['webp'] = $support['webp']
				? self::convert_one( $source_path, 'webp', $quality, $support['backend'] )
				: [ 'done' => false, 'reason' => 'format_unavailable' ];
		}

		if ( $want_avif ) {
			$result['avif'] = $support['avif']
				? self::convert_one( $source_path, 'avif', $quality, $support['backend'] )
				: [ 'done' => false, 'reason' => 'format_unavailable' ];
		}

		$result['ok'] = ! empty( $result['webp']['done'] ) || ! empty( $result['avif']['done'] );
		return $result;
	}

	/**
	 * Path of the converted variant: foo.jpg + webp → foo.jpg.webp
	 */
	public static function variant_path( string $source_path, string $format ): string {
		return $source_path . '.' . strtolower( $format );
	}

	/**
	 * @return array{webp:bool, avif:bool, backend:string}
	 */
	public static function supported_formats(): array {
		static $cache = null;
		if ( $cache !== null ) {
			return $cache;
		}

		$webp = $avif = false;
		$backend = 'none';

		if ( class_exists( '\Imagick' ) ) {
			try {
				$formats = array_map( 'strtoupper', (array) \Imagick::queryFormats() );
				if ( in_array( 'WEBP', $formats, true ) ) { $webp = true; }
				if ( in_array( 'AVIF', $formats, true ) ) { $avif = true; }
				if ( $webp || $avif ) { $backend = 'imagick'; }
			} catch ( \Throwable $e ) {
				// Fall back to GD.
			}
		}

		if ( function_exists( 'gd_info' ) ) {
			$gd = gd_info();
			if ( ! $webp && ! empty( $gd['WebP Support'] ) ) {
				$webp = true;
				if ( $backend === 'none' ) { $backend = 'gd'; }
			}
			if ( ! $avif && function_exists( 'imageavif' ) && ! empty( $gd['AVIF Support'] ) ) {
				$avif = true;
				if ( $backend === 'none' ) { $backend = 'gd'; }
			}
		}

		$cache = [ 'webp' => $webp, 'avif' => $avif, 'backend' => $backend ];
		return $cache;
	}

	// -------------------------------------------------------------------------
	// Internal helpers
	// -------------------------------------------------------------------------

	/** @return array{done:bool, reason?:string, bytes?:int, saved?:int} */
	private static function convert_one( string $source_path, string $format, int $quality, string $backend ): array {
		$target = self::variant_path( $source_path, $format );

		// mtime cache: variant is up to date → skip.
		if ( is_file( $target ) ) {
			$src_mtime = (int) @filemtime( $source_path );
			$tgt_mtime = (int) @filemtime( $target );
			if ( $tgt_mtime >= $src_mtime && $src_mtime > 0 ) {
				return [ 'done' => true, 'reason' => 'cached', 'bytes' => (int) @filesize( $target ) ];
			}
		}

		try {
			$ok = $backend === 'imagick'
				? self::convert_with_imagick( $source_path, $target, $format, $quality )
				: self::convert_with_gd( $source_path, $target, $format, $quality );
		} catch ( \Throwable $e ) {
			Logger::warning( 'ml.image.convert', $e->getMessage(), [
				'path'   => basename( $source_path ),
				'format' => $format,
			] );
			return [ 'done' => false, 'reason' => 'exception' ];
		}

		if ( ! $ok || ! is_file( $target ) ) {
			return [ 'done' => false, 'reason' => 'encode_failed' ];
		}

		$src_bytes = (int) @filesize( $source_path );
		$dst_bytes = (int) @filesize( $target );

		if ( $dst_bytes === 0 ) {
			wp_delete_file( $target );
			return [ 'done' => false, 'reason' => 'empty_output' ];
		}

		// Variant is larger than the original → no benefit, delete it.
		if ( $dst_bytes >= $src_bytes ) {
			wp_delete_file( $target );
			return [ 'done' => false, 'reason' => 'no_gain' ];
		}

		Logger::info( 'ml.image.convert', basename( $source_path ), [
			'format' => $format,
			'before' => $src_bytes,
			'after'  => $dst_bytes,
			'saved'  => $src_bytes - $dst_bytes,
		] );

		return [ 'done' => true, 'bytes' => $dst_bytes, 'saved' => $src_bytes - $dst_bytes ];
	}

	private static function convert_with_imagick( string $source, string $target, string $format, int $quality ): bool {
		$im = new \Imagick( $source );
		try {
			$im->setImageFormat( $format );
			$im->setImageCompressionQuality( $quality );
			if ( $format === 'avif' ) {
				@$im->setOption( 'heic:speed', '5' );
				@$im->setOption( 'avif:speed', '5' );
			}
			$blob = $im->getImageBlob();
		} finally {
			$im->clear();
			$im->destroy();
		}
		return self::atomic_write( $target, $blob );
	}

	private static function convert_with_gd( string $source, string $target, string $format, int $quality ): bool {
		$info = @getimagesize( $source );
		if ( ! $info ) {
			return false;
		}
		$img = match ( $info['mime'] ?? '' ) {
			'image/jpeg' => @imagecreatefromjpeg( $source ),
			'image/png'  => self::create_png( $source ),
			'image/gif'  => @imagecreatefromgif( $source ),
			default      => false,
		};

		if ( ! $img ) {
			return false;
		}

		ob_start();
		try {
			$ok = match ( $format ) {
				'webp' => @imagewebp( $img, null, $quality ),
				'avif' => function_exists( 'imageavif' ) ? @imageavif( $img, null, $quality ) : false,
				default => false,
			};
			$blob = (string) ob_get_clean();
		} catch ( \Throwable $e ) {
			ob_end_clean();
			unset( $img );
			throw $e;
		}
		// unset(), not imagedestroy(): a GdImage is freed with its last
		// reference since PHP 8.0, and PHP 8.5 deprecates imagedestroy().
		unset( $img );

		if ( ! $ok || $blob === '' ) {
			return false;
		}
		return self::atomic_write( $target, $blob );
	}

	private static function create_png( string $source ): \GdImage|false {
		$img = @imagecreatefrompng( $source );
		if ( $img ) {
			imagepalettetotruecolor( $img );
			imagealphablending( $img, true );
			imagesavealpha( $img, true );
		}
		return $img;
	}

	private static function atomic_write( string $path, string $blob ): bool {
		$tmp = $path . '.dytmp';
		// Direct write + atomic rename: WP_Filesystem has no atomic-replace primitive,
		// and the temp file lives in the same uploads dir we just wrote to.
		if ( @file_put_contents( $tmp, $blob ) === false ) { // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents, WordPress.PHP.NoSilencedErrors.Discouraged -- atomic write of a freshly-encoded image variant
			return false;
		}
		if ( ! @rename( $tmp, $path ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions.rename_rename, WordPress.PHP.NoSilencedErrors.Discouraged -- atomic replace; no WP_Filesystem equivalent
			wp_delete_file( $tmp );
			return false;
		}
		return true;
	}

	private static function is_animated_gif( string $path ): bool {
		// Streamed binary read to count GIF frame separators without loading the
		// whole file into memory; WP_Filesystem only offers full-file reads.
		$fh = @fopen( $path, 'rb' ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fopen, WordPress.PHP.NoSilencedErrors.Discouraged -- chunked binary read, see above
		if ( ! $fh ) {
			return false;
		}
		$count = 0;
		while ( ! feof( $fh ) && $count < 2 ) {
			$chunk = fread( $fh, 1024 * 100 ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fread -- chunked binary read, see above
			if ( $chunk === false ) { break; }
			$count += (int) preg_match_all( '#\x00\x21\xF9\x04.{4}\x00[\x2C\x21]#s', $chunk );
		}
		fclose( $fh ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fclose -- chunked binary read, see above
		return $count > 1;
	}
}
