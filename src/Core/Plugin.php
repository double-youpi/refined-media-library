<?php declare(strict_types=1);
namespace DoubleYoupi\Core;

use DoubleYoupi\Admin\Access;
use DoubleYoupi\Admin\AdminMenu;
use DoubleYoupi\Admin\DyShell;
use DoubleYoupi\Admin\Feedback;
use DoubleYoupi\Admin\OverviewPage;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Main bootstrap — SOLO VERSION (generated in WordPress.org builds).
 *
 * Decoupled from the suite: no licensing, no reference to any specific module.
 * The boot sequence remains predictable (textdomain → migrations →
 * overview → modules → menu), but everything specific to the bundled module
 * (default options, activation callbacks) lives in SoloConfig,
 * generated by the build from build/configs/{slug}.php.
 *
 * DO NOT edit in a generated solo plugin: the source of truth is
 * build/standalone/shell/Plugin.php in the Double Youpi monorepo.
 */
final class Plugin {

	private static ?Plugin $instance = null;

	public static function instance(): Plugin {
		if ( self::$instance === null ) {
			self::$instance = new self();
		}
		return self::$instance;
	}

	private bool $booted = false;

	public function boot(): void {
		// Two standalone builds can be active at once (Refined Admin Dashboard
		// and Refined Media Library): each calls boot() on this shared
		// singleton. The first wins, the second would only add every hook a
		// second time.
		if ( $this->booted ) {
			// The one-time setup is done. Still pick up any module the other
			// build registered after we booted: the registry starts only what
			// it has not started yet.
			ModuleRegistry::boot();
			return;
		}
		$this->booted = true;

		// Translations on init@1 — avoids the "textdomain loaded too early" notice (WP 6.7+).
		// We keep load_plugin_textdomain() because translations are BUNDLED and
		// just-in-time loading from the plugin directory is only automatic
		// from WP 6.7 onward — we support WP 6.5+.
		add_action( 'init', static function (): void {
			// phpcs:ignore WordPressVIPMinimum.Functions.RestrictedFunctions.i18n_load_plugin_textdomain, PluginCheck.CodeAnalysis.DiscouragedFunctions.load_plugin_textdomainFound -- bundled translations require explicit path registration on WP 6.5/6.6
			load_plugin_textdomain(
				SoloConfig::text_domain(),
				false,
				dirname( DOUBLEYOUPI_BASENAME ) . '/languages'
			);
		}, 1 );

		/*
		 * Migrations on init@5 — never earlier.
		 *
		 * They run the activation callbacks, and those register taxonomies whose
		 * labels are translated. Called from plugins_loaded, that asks WordPress
		 * for a translation before the textdomain exists, which WP 6.7+ reports
		 * on screen as "Translation loading … was triggered too early" — visible
		 * to the user on the first page load after every update.
		 *
		 * init@5 sits after the textdomain (init@1) and before the modules
		 * register their own taxonomies (init@10), so the flush_rewrite_rules()
		 * at the end of Installer::run() still sees them registered.
		 */
		add_action( 'init', [ $this, 'maybe_run_migrations' ], 5 );

		// Overview page — registered BEFORE modules so it lands in
		// the first menu position (the plugin's home).
		OverviewPage::register();

		// Boot all modules registered via ModuleRegistry.
		ModuleRegistry::boot();

		// Who may change Double Youpï (doubleyoupi_manage), before any menu asks.
		Access::register();

		// Double Youpi menu — brand consistency preserved even in solo builds.
		AdminMenu::register();

		// Standalone Double Youpi admin skin (dark) on DY pages. In solo builds, the
		// Admin module is not bundled → this skin is always applied.
		DyShell::register();

		// "Send feedback about this screen" (admin-bar button + dialog + REST
		// relay). Opt-in on every report, see Admin\Feedback.
		//
		// Only when the build actually bundles it: a solo that talks to an
		// external service must declare it in its readme, with links to the
		// service's terms and privacy policy (WordPress.org guidelines). A build
		// that cannot make that declaration ships without the feature rather
		// than shipping an undeclared one.
		if ( class_exists( Feedback::class ) ) {
			Feedback::register();
		}

	}

	/**
	 * Idempotent migrations driven by SoloConfig. Sets default options and
	 * runs activation callbacks (taxonomy registration, etc.) on first load
	 * and on each version upgrade. No-op if already up to date.
	 *
	 * Public because it is hooked on init@5 — do not call it directly.
	 */
	public function maybe_run_migrations(): void {
		$option    = SoloConfig::installed_version_option();
		$installed = (string) get_option( $option, '0.0.0' );
		if ( version_compare( $installed, DOUBLEYOUPI_VERSION, '>=' ) ) {
			return;
		}

		Installer::run();

		update_option( $option, DOUBLEYOUPI_VERSION, false );
	}
}
